import {act,renderHook,waitFor} from '@testing-library/react';
import {it,expect,vi} from 'vitest';
import {PageContextProvider} from '../PageContextProvider';
import type {PageSnapshot,PageStore} from '../../lib/browser-bridge';
import {useRobotsStatus} from './useRobotsStatus';
import {requestTool} from '../../tools/transport';
vi.mock('../../tools/transport',()=>({requestTool:vi.fn()}));
it('invalidates on edits, navigation and reload; late replies cannot replace a newer result',async()=>{
 let state:PageSnapshot={context:{url:'https://first.test/',tabId:1,source:'tab'},connection:{status:'connected',tabCount:1},tabs:[{id:1,url:'https://first.test/',title:'First',documentToken:'a'}]};
 const listeners=new Set<()=>void>();
 const store={getSnapshot:()=>state,subscribe:(f:()=>void)=>{listeners.add(f);return()=>{listeners.delete(f);};},start:()=>()=>{}} as PageStore;
 const replies:((data:unknown)=>void)[]=[];
 vi.mocked(requestTool).mockImplementation(()=>new Promise(resolve=>replies.push(resolve)));
 const {result,rerender}=renderHook(({draft})=>useRobotsStatus(draft),{initialProps:{draft:state.context.url},wrapper:({children})=><PageContextProvider store={store}>{children}</PageContextProvider>});
 const reply=(url:string,content:string)=>({id:1,url,documentId:'doc',entries:[{name:'robots',content}],headers:[]});
 expect(result.current.state).toBe('unknown');
 act(()=>{state={...state,context:{...state.context,url:'https://second.test/'}};listeners.forEach(f=>f());});
 rerender({draft:state.context.url});
 await act(async()=>replies[1](reply(state.context.url,'noindex')));
 expect(result.current.index).toBe('noindex');
 await act(async()=>replies[0](reply('https://first.test/','index, follow')));
 expect(result.current.index).toBe('noindex');
 rerender({draft:'https://typing.test/'});expect(result.current.state).toBe('unknown');
 rerender({draft:state.context.url});
 act(()=>{state={...state,tabs:[{...state.tabs[0],documentToken:'new-document'}]};listeners.forEach(f=>f());});
 expect(result.current.state).toBe('unknown');
 await act(async()=>replies.at(-1)!(reply(state.context.url,'index,follow')));
 await waitFor(()=>expect(result.current.state).toBe('allowed'));
});
