import { StrictMode } from 'react';
import { createRoot } from 'react-dom/client';
import { PreferencesProvider } from '../../app/PreferencesProvider';
import { PageContextProvider } from '../../app/PageContextProvider';
import { createPreferencesStore } from '../../lib/preferences';
import { VisualLab } from './VisualLab';
import { VisualScene } from './VisualScene';
import { parseVisual } from './design';
import '../../styles/app.css';
import '../header-responsive-lab/responsive-lab.css';
import './visual-lab.css';
const params = new URLSearchParams(location.search);
const scene = params.get('view') === 'scene';
const visual = parseVisual(params.get('variant'));
const theme = params.get('theme') === 'light' ? 'light' : 'dark';
const preferences = createPreferencesStore({ storagePrefix: `axolotl-visual-lab-${scene ? visual : 'shell'}`, initialTheme: theme });
preferences.set('theme', theme);
document.body.classList.add(scene ? 'hr-scene-page' : 'hr-lab-page');
createRoot(document.getElementById('axolotl-root')!).render(<StrictMode><PreferencesProvider store={preferences}><PageContextProvider>{scene ? <VisualScene visual={visual}/> : <VisualLab/>}</PageContextProvider></PreferencesProvider></StrictMode>);
